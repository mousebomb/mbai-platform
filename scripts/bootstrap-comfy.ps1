# 一次性引导：拉 ComfyUI（固定 commit）→ 生成模型路径挂载 → 建 venv → 装依赖
#
# 用法（默认读仓库根 .env 的 PLATFORM_MODELS_DIR / PLATFORM_EXTRA_MODEL_DIRS）：
#   powershell -ExecutionPolicy Bypass -File scripts\bootstrap-comfy.ps1
# 换机器 / 换盘：
#   powershell -ExecutionPolicy Bypass -File scripts\bootstrap-comfy.ps1 `
#       -ModelsDir 'E:\models' -ExtraModelDirs 'F:\AI\ComfyUI\models'
#
# 说明：
#   - 固定 commit 是硬约束：MOSS-Image 的原生节点只进了 master 的某个点之后，浮动分支会漂
#   - extra_model_paths.yaml 由本脚本生成，只做只读挂载，绝不复制权重
param(
    [string]$ComfySha = 'd07dff45',
    [string]$ComfyRepo = 'https://github.com/comfyanonymous/ComfyUI.git',
    [string]$ModelsDir = '',
    # 历史权重目录：只读挂载。不存在的会被跳过，所以空值对新机器无害
    [string[]]$ExtraModelDirs = @(),
    [switch]$SkipEnv
)

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$comfy = Join-Path $root 'engines\comfy'

# 从 .env 取一个值：没传参数时用它，保证「平台读的」和「引导脚本读的」是同一份配置
function Get-DotEnvValue {
    param([string]$Key)
    $envFile = Join-Path $root '.env'
    if (-not (Test-Path $envFile)) { return '' }
    foreach ($line in Get-Content $envFile -Encoding UTF8) {
        if ($line -match "^\s*$Key\s*=\s*(.+?)\s*$") { return $Matches[1].Trim('"').Trim("'") }
    }
    return ''
}

if (-not $ModelsDir) { $ModelsDir = Get-DotEnvValue 'PLATFORM_MODELS_DIR' }
if (-not $ModelsDir) {
    throw '没有模型池路径：在 .env 里配 PLATFORM_MODELS_DIR（模板 .env.example），或传 -ModelsDir'
}
if ($ExtraModelDirs.Count -eq 0) {
    # .env 里是 JSON 数组，省得再引一个 JSON 解析依赖：只处理最常见的一层字符串数组
    $raw = Get-DotEnvValue 'PLATFORM_EXTRA_MODEL_DIRS'
    if ($raw -match '^\[(.*)\]$') {
        $ExtraModelDirs = @(
            $Matches[1].Split(',') |
                ForEach-Object { $_.Trim().Trim('"').Trim("'") } |
                Where-Object { $_ }
        )
    }
}

# ---------- 1. 仓库对齐到固定 commit ----------
if (Test-Path (Join-Path $comfy '.git')) {
    # 本地已经有目标 commit 就不联网：常见坑是 git 全局代理指向已关闭的本地端口，fetch 必失败
    git -C $comfy cat-file -e "$ComfySha^{commit}" 2>$null
    if ($LASTEXITCODE -eq 0) {
        Write-Host "[1/4] commit $ComfySha already present, skip fetch"
    }
    else {
        Write-Host "[1/4] repo exists, fetch $ComfySha"
        git -C $comfy fetch origin
        if ($LASTEXITCODE -ne 0) {
            throw "git fetch failed ($LASTEXITCODE)：检查 git 代理配置（git config --global http.proxy）是否指向了没启动的端口"
        }
    }
}
else {
    Write-Host '[1/4] clone ComfyUI'
    New-Item -ItemType Directory -Force -Path (Split-Path $comfy -Parent) | Out-Null
    # blob:none 只拉提交树，按需取文件，省一半以上流量
    git clone --filter=blob:none $ComfyRepo $comfy
    if ($LASTEXITCODE -ne 0) { throw "git clone failed ($LASTEXITCODE)" }
}

git -C $comfy checkout --detach $ComfySha
if ($LASTEXITCODE -ne 0) { throw "checkout $ComfySha failed ($LASTEXITCODE)" }
Write-Host "      HEAD -> $ComfySha"

# ---------- 2. 生成 extra_model_paths.yaml ----------
Write-Host '[2/4] write extra_model_paths.yaml'

# ComfyUI 认的目录键。少写一个键 = 那类模型直接不可见，所以按全集写
$keys = @(
    'checkpoints', 'clip', 'clip_vision', 'configs', 'controlnet', 'diffusion_models',
    'embeddings', 'gligen', 'hypernetworks', 'loras', 'photomaker', 'style_models',
    'text_encoders', 'unet', 'upscale_models', 'vae', 'vae_approx',
    'animatediff_models', 'animatediff_motion_lora',
    'insightface', 'facerestore_models', 'sams', 'sam2', 'onnx',
    # 抠图（BiRefNet）走核心的 LoadBackgroundRemovalModel，目录键是 background_removal
    'background_removal'
)

function New-PoolBlock {
    param([string]$Name, [string]$BasePath)
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine("${Name}:")
    [void]$sb.AppendLine("  base_path: $BasePath")
    foreach ($k in $keys) { [void]$sb.AppendLine("  ${k}: $k") }
    return $sb.ToString()
}

$yaml = @()
# 注释保持纯 ASCII：ComfyUI 用 open() 默认编码读这个文件，Windows 上是 GBK，中文会乱码甚至解析失败
$yaml += '# Generated by scripts/bootstrap-comfy.ps1 - do not edit by hand'
$yaml += '# Read-only mounts: platform pool first, then legacy weights. Weights are never copied.'
$yaml += ''
$yaml += New-PoolBlock -Name 'ai_pool' -BasePath ($ModelsDir -replace '\\', '/')

$n = 1
foreach ($dir in $ExtraModelDirs) {
    if (-not (Test-Path $dir)) {
        Write-Host "      skip missing extra dir: $dir"
        continue
    }
    $yaml += New-PoolBlock -Name "extra_$n" -BasePath ($dir -replace '\\', '/')
    $n++
}

$yamlPath = Join-Path $comfy 'extra_model_paths.yaml'
# 显式 UTF-8 无 BOM：ComfyUI 的 YAML 解析对 BOM 不友好，PowerShell 5.1 的 -Encoding utf8 会加 BOM
[IO.File]::WriteAllText($yamlPath, ($yaml -join "`n") + "`n", (New-Object System.Text.UTF8Encoding($false)))
Write-Host "      -> $yamlPath"

# ---------- 3. venv ----------
$py = Join-Path $comfy '.venv\Scripts\python.exe'
if (Test-Path $py) {
    Write-Host "[3/4] venv exists: $py"
}
else {
    Write-Host '[3/4] create venv (python 3.12)'
    uv venv --python 3.12 (Join-Path $comfy '.venv')
    if ($LASTEXITCODE -ne 0) { throw "uv venv failed ($LASTEXITCODE)" }
}

# ---------- 4. 依赖 ----------
if ($SkipEnv) {
    Write-Host '[4/4] skipped (-SkipEnv)'
}
else {
    Write-Host '[4/4] install torch cu130 + requirements'
    & (Join-Path $PSScriptRoot 'install-comfy-env.ps1')
    if ($LASTEXITCODE -ne 0) { throw "install-comfy-env failed ($LASTEXITCODE)" }
}

Write-Host 'DONE: next -> uv run python scripts\download-models.py, then scripts\start-engine.ps1'
